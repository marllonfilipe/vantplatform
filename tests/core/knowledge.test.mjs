    const deal=(await admin.query(`INSERT INTO vant.deals(tenant_id,owner_id,lead_id,pipeline_id,stage_id,name,amount_cents,probability,close_on)
      VALUES($1,$2,$3,$4,$5,'Proposta',10000,40,current_date-1) RETURNING id`,[tenants[0],member.id,lead.id,pipeline,stage])).rows[0].id;
    const dealRun=await call('core/deals/'+deal+'/analyses','POST',owner,{});
    assert.equal(dealRun.status,201);
    const dealResult=(await dealRun.json()).result;
    assert.equal(dealResult.probability,40);
    assert.equal(dealResult.classification,'Risco elevado');
    assert.equal(dealResult.recovery.status,'open');
    assert.equal(dealResult.recovery.questions.length,2);
    const newRun=await call(leadPath,'POST',owner,{});
    assert.equal((await newRun.json()).result.score,55);
    const history=await (await call(leadPath,'GET',owner)).json();
    assert.deepEqual(history.items.map(r=>r.result.score),[55,20]);
    assert.equal(history.items[0].result.qualification.interest,'Não informado');
    assert.equal((await call('crm/leads/'+lead.id,'PATCH',owner,{purchase_intent:'invalid'})).status,400);
    const offer={category:'offer',title:'Gestão de cobrança',content:'Reduzir tempo de cobrança. Varejo Compras'};
    assert.equal((await call(path,'POST',other,offer)).status,201);
    const updated=await call('crm/leads/'+lead.id,'PATCH',owner,{purchase_intent:'requested_proposal',budget_state:'confirmed',purchase_window:'month',stated_need:'Reduzir tempo de cobrança.'});
    assert.equal(updated.status,200);
    const taskResponse=await call('crm/activities','POST',owner,{kind:'task',title:'Revisar escopo',lead_id:lead.id});
    assert.equal(taskResponse.status,201);
    const task=(await taskResponse.json()).id;
    const noOffer=await (await call(leadPath,'POST',owner,{})).json();
    assert.equal(noOffer.result.offer,undefined);
    assert.equal(noOffer.result.activities.pending[0].id,task);
    assert.deepEqual(noOffer.result.activities.completed,[]);
    assert.equal((await call('crm/activities/'+task,'PATCH',owner,{done_at:new Date().toISOString()})).status,200);
    const catalogId=(await (await call(path,'POST',owner,offer)).json()).id;
    const informed=await (await call(leadPath,'POST',owner,{})).json();
    assert.equal(informed.result.qualification.budget,'Confirmado');
    assert.equal(informed.result.qualification.need,'Reduzir tempo de cobrança.');
    assert.deepEqual(informed.result.activities.pending,[]);
    assert.equal(informed.result.activities.completed[0].id,task);
    assert.equal(informed.result.activities.completed[0].owner_id,member.id);
    assert.equal(informed.result.offer.document_id,catalogId);
    assert.equal(informed.result.offer.revision,1);
    assert.equal((await call(path+'/'+catalogId,'PUT',owner,{...offer,title:'Nova oferta'})).status,200);
    assert.equal((await (await call(path,'GET',owner)).json()).items.find(r=>r.id===catalogId).revision,2);
    assert.match(informed.result.nextAction,/Preparar proposta/);
    const previous=await (await call(leadPath,'GET',owner)).json();
    assert.equal(previous.items[2].result.qualification.budget,'Não informado');
    assert.equal(previous.items[1].result.activities.pending[0].id,task);
    const metrics=await call('core/metrics?days=7','GET',owner);
    assert.equal(metrics.status,200);
    const measured=(await metrics.json()).items;
    assert.deepEqual(measured.map(item=>[item.subject_kind,item.runs]),[['deal',1],['lead',4]]);
    assert.ok(measured.every(item=>item.p95_ms>=item.p50_ms && item.p50_ms>0));
    assert.equal((await call('core/metrics','GET',seller)).status,403);
    assert.equal((await call('core/metrics?days=1','GET',owner)).status,400);
    assert.deepEqual((await (await call('core/metrics','GET',other)).json()).items,[]);
    const proposalPath='agents/proposals/'+informed.id;
    assert.equal((await call(proposalPath,'GET',other)).status,404);
    assert.equal((await call(proposalPath,'POST',seller,{})).status,403);
    assert.equal((await call(proposalPath,'POST',owner,{})).status,201);
    assert.equal((await (await call(proposalPath,'GET',owner)).json()).proposal.status,'pending');
    assert.equal((await call(proposalPath+'/approve','POST',seller,{})).status,403);
    assert.equal((await call(proposalPath+'/approve','POST',owner,{due_at:'bad-date'})).status,400);
    const countTasks=async()=> (await admin.query('SELECT count(*)::int AS n FROM vant.activities WHERE tenant_id=$1 AND lead_id=$2 AND title=$3',[tenants[0],lead.id,informed.result.nextAction])).rows[0].n;
    assert.equal(await countTasks(),0);
    const approvals=await Promise.all([1,2].map(()=>call(proposalPath+'/approve','POST',owner,{})));
    assert.ok(approvals.every(res=>res.status===200));
    const [first,second]=await Promise.all(approvals.map(res=>res.json()));
    assert.equal(first.status,'approved');
    assert.equal(first.activity_id,second.activity_id);
    assert.equal(await countTasks(),1);
    assert.equal((await call(proposalPath+'/cancel','POST',owner,{})).status,409);
    const cancelled='agents/proposals/'+noOffer.id;
    assert.equal((await call(cancelled,'POST',owner,{})).status,201);
    assert.equal((await (await call(cancelled+'/cancel','POST',owner,{})).json()).status,'cancelled');
    assert.equal((await call(cancelled+'/approve','POST',owner,{})).status,409);
    assert.equal(await countTasks(),1);
    const consult=async(cookie,question)=> {
      const res=await call('agents/copilot','POST',cookie,{question});
      assert.equal(res.status,200);
      return res.json();
    };
    const leadsQuestion='Quais leads devo priorizar hoje?';
    const priorities=await consult(owner,leadsQuestion);
    assert.equal(priorities.intent,'leads');
    assert.deepEqual(priorities.items.map(row=>[row.id,row.score]),[[lead.id,55]]);
    assert.deepEqual((await consult(other,leadsQuestion)).items,[]);
    assert.deepEqual((await consult(seller,leadsQuestion)).items,[]);
    const risks=await consult(owner,'Quais oportunidades estão em risco?');
    assert.equal(risks.intent,'risks');
    assert.equal(risks.items[0].id,deal);
    assert.equal(risks.items[0].risk,'Risco elevado');
    const overdue=await call('crm/activities','POST',owner,{kind:'followup',title:'Retornar proposta',lead_id:lead.id,due_at:'2020-01-01T12:00:00Z'});
    assert.equal(overdue.status,201);
    const followups=await consult(owner,'Quais follow-ups estão atrasados?');
    assert.equal(followups.intent,'followups');
    assert.equal(followups.items[0].id,(await overdue.json()).id);
    const unrelated=await consult(owner,'Qual é a composição química da atmosfera de Marte?');
    assert.equal(unrelated.intent,null);
    const scheduled=await call('crm/activities','POST',owner,{kind:'meeting',title:'Revisão da proposta',lead_id:lead.id,deal_id:deal});
    const meeting=(await scheduled.json()).id;
    const briefing='agents/meetings/'+meeting+'/briefs';
    assert.equal((await call(briefing,'POST',other,{})).status,404);
    assert.equal((await call(briefing,'POST',seller,{})).status,404);
    assert.equal((await call('agents/meetings/'+task+'/briefs','POST',owner,{})).status,404);
    const prepared=await call(briefing,'POST',owner,{});
    assert.equal(prepared.status,201);
    const brief=await prepared.json();
    assert.equal(brief.result.lead.stated_need,'Reduzir tempo de cobrança.');
    assert.equal(brief.result.deal.id,deal);
    assert.equal(brief.result.history[0].id,task);
    assert.deepEqual(brief.result.questions,['Qual próximo passo e quem ficará responsável?']);
    assert.ok(brief.result.sources.every(source=>source.document_id!==undefined&&source.revision>0));
    assert.equal((await (await call(briefing,'GET',owner)).json()).items[0].id,brief.id);
    const minutes='agents/meetings/'+meeting+'/minutes';
    const notes='O cliente pediu integração ao CRM. A equipe aprovou a proposta. O gestor enviará o contrato amanhã. A implantação começa em janeiro.';
    const payload={expectedRevision:0,notes};
    assert.equal((await call(minutes,'POST',owner,payload)).status,409);
    assert.equal((await call('crm/activities/'+meeting,'PATCH',owner,{done_at:new Date().toISOString()})).status,200);
    assert.equal((await call(minutes,'POST',other,payload)).status,404);
    assert.equal((await call(minutes,'POST',seller,payload)).status,404);
    const saved=await call(minutes,'POST',owner,payload);
    assert.equal(saved.status,201);
    const firstNotes=await saved.json();
    assert.equal(firstNotes.revision,1);
    assert.equal(firstNotes.excerpts.length,3);
    assert.ok(firstNotes.excerpts.every(line=>notes.includes(line.text)));
    assert.equal((await call(minutes,'POST',owner,payload)).status,200);
    assert.equal((await call(minutes,'POST',owner,{...payload,notes:'Texto concorrente.'})).status,409);
    const revised=await call(minutes,'POST',owner,{expectedRevision:1,notes:'O contrato foi aprovado.'});
    assert.equal(revised.status,201);
    const recorded=await (await call(minutes,'GET',owner)).json();
    assert.deepEqual(recorded.items.map(item=>item.revision),[2,1]);
    assert.equal(recorded.items[1].notes,notes);
    const stalledQuestion='Quais oportunidades estão paradas?';
    await admin.query("UPDATE vant.deals SET updated_at=now()-interval '20 days' WHERE id=$1",[deal]);
    // A reunião concluída é um contato recente, mesmo com a ficha antiga.
    assert.deepEqual((await consult(owner,stalledQuestion)).items,[]);
    await admin.query("UPDATE vant.activities SET done_at=now()-interval '18 days' WHERE id=$1",[meeting]);
    const stalled=await consult(owner,stalledQuestion);
    assert.equal(stalled.intent,'stalled');
    assert.equal(stalled.items[0].id,deal);
    assert.equal(stalled.items[0].days_stalled,18);
    assert.deepEqual((await consult(other,stalledQuestion)).items,[]);
    assert.deepEqual((await consult(seller,stalledQuestion)).items,[]);
    const staleRun=await (await call('core/deals/'+deal+'/analyses','POST',owner,{})).json();
    const stalePath='agents/proposals/'+staleRun.id;
    assert.equal((await call(stalePath,'POST',owner,{})).status,201);
    assert.equal((await call('crm/deals/'+deal,'PATCH',owner,{status:'lost',loss_reason:'Orçamento indisponível.'})).status,200);
    assert.equal((await call(stalePath+'/approve','POST',owner,{})).status,409);
    const lostRun=await (await call('core/deals/'+deal+'/analyses','POST',owner,{})).json();
    assert.equal(lostRun.result.recovery.status,'lost');
    assert.equal(lostRun.result.recovery.reason,'Orçamento indisponível.');
    assert.deepEqual((await consult(owner,stalledQuestion)).items,[]);
    const sellerId=(await admin.query("SELECT id FROM vant.members WHERE tenant_id=$1 AND role='seller'",[tenants[0]])).rows[0].id;
    await admin.query(`INSERT INTO vant.deals(tenant_id,owner_id,pipeline_id,stage_id,name,amount_cents,probability,status,closed_at)
      VALUES($1,$2,$4,$5,'Venda recente',10001,100,'won',now()),($1,$3,$4,$5,'Venda da carteira',40000,100,'won',now()),
      ($1,$3,$4,$5,'Fora do período',50000,100,'won',now()-interval '40 days'),($1,$2,$4,$5,'Em negociação',16001,50,'open',null)`,[tenants[0],member.id,sellerId,pipeline,stage]);
