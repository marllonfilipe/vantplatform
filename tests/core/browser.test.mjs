import {test} from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import pg from 'pg';
import {chromium} from 'playwright-core';
import {createApp} from '../../src/app.mjs';
import {createPool} from '../../src/db.mjs';
import {hashPassword} from '../../src/security.mjs';
import {featureRoutes} from '../../src/routes.mjs';
import {servePage} from '../../src/pages.mjs';
import {stopInference} from '../../src/inference.mjs';

test('gestor indexa e consulta política comercial no Chromium',async()=>{
  assert.equal(process.env.APP_ENV,'test');
  const admin=new pg.Client({connectionString:process.env.ADMIN_DATABASE_URL});
  await admin.connect();
  const pool=createPool(process.env.DATABASE_URL);
  const port=3193, origin='http://127.0.0.1:'+port;
  const server=createApp({pool,origin,environment:'test',featureRoutes,servePage});
  let browser;
  try {
    const tenant=randomUUID(), password=randomUUID(), email='memoria@example.invalid';
    await admin.query("INSERT INTO vant.tenants(id,name) VALUES($1,'Memória')",[tenant]);
    await admin.query("INSERT INTO vant.members(tenant_id,email,name,role,password_hash) VALUES($1,$2,'Gestora','owner',$3)",[tenant,email,await hashPassword(password)]);
    await new Promise((resolve,reject)=>{server.once('error',reject);server.listen(port,'127.0.0.1',resolve);});
    browser=await chromium.launch({executablePath:process.env.CHROME_BIN??'/usr/bin/google-chrome',args:['--no-sandbox']});
    const page=await browser.newPage();
    await page.goto(origin);
    await page.getByLabel('Identificador da empresa').fill(tenant);
    await page.getByLabel('E-mail',{exact:true}).fill(email);
    await page.getByLabel('Senha').fill(password);
    await page.getByRole('button',{name:'Entrar'}).click();
    await page.getByRole('button',{name:'Memória comercial'}).click();
    await page.getByRole('button',{name:'Adicionar documento'}).click();
    await page.getByLabel('Título',{exact:true}).fill('Prazo padrão');
    await page.getByLabel('Texto do documento').fill('A proposta comercial vale quinze dias.');
    await page.getByRole('button',{name:'Indexar documento'}).click();
    await page.getByText('Prazo padrão',{exact:true}).waitFor();
    await page.getByLabel('Pesquisar na memória comercial').fill('Qual é a validade da proposta?');
    await page.getByRole('button',{name:'Buscar trechos'}).click();
    await page.getByText('A proposta comercial vale quinze dias.',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Substituir'}).click();
    await page.getByLabel('Novo texto integral').fill('A proposta comercial vale dez dias.');
    await page.getByRole('button',{name:'Indexar documento'}).click();
    await page.getByRole('dialog').waitFor({state:'hidden'});
    await page.getByRole('button',{name:'Excluir',exact:true}).click();
    await page.getByRole('button',{name:'Confirmar exclusão'}).click();
    await page.getByText('Nenhum documento indexado.').waitFor();
    const created=await page.evaluate(async()=> {
      const response=await fetch('/api/v1/crm/leads',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({name:'Conta piloto'})});
      return response.status;
    });
    assert.equal(created,201);
    await page.getByRole('button',{name:'Leads',exact:true}).click();
    await page.getByRole('button',{name:'Conta piloto',exact:true}).click();
    await page.getByRole('button',{name:'Analisar no Intelligence Core'}).click();
    await page.getByRole('button',{name:'Registrar respostas do SDR'}).click();
    await page.getByLabel('Que problema você precisa resolver e qual resultado espera?').fill('Reduzir prazo da proposta.');
    await page.getByRole('button',{name:'Salvar respostas'}).click();
    await page.getByRole('button',{name:'Atualizar análise'}).click();
    await page.getByText('Reduzir prazo da proposta.',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Preparar tarefa sugerida'}).click();
    await page.getByText('Aguardando decisão',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Aprovar e criar tarefa'}).click();
    await page.getByText('Aprovada',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Fechar',exact:true}).click();
    await page.getByRole('button',{name:'Agenda comercial',exact:true}).click();
    await page.getByRole('button',{name:'Obter um canal de contato.',exact:true}).waitFor();
    await page.getByRole('button',{name:'Visão geral',exact:true}).click();
    await page.getByRole('button',{name:'Abrir copiloto comercial'}).click();
    await page.getByRole('button',{name:'Quais leads devo priorizar hoje?'}).click();
    await page.getByRole('heading',{name:'Conta piloto',exact:true}).waitFor();
    const scheduled=await page.evaluate(async()=>{
      const res=await fetch('/api/v1/crm/activities',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({title:'Revisão de escopo',kind:'meeting'})});
      return res.status;
    });
    assert.equal(scheduled,201);
    await page.getByRole('button',{name:'Agenda comercial',exact:true}).click();
    await page.getByRole('button',{name:'Revisão de escopo',exact:true}).click();
    await page.getByRole('button',{name:'Preparar reunião',exact:true}).click();
    await page.getByRole('heading',{name:'Perguntas para a reunião'}).waitFor();
    await page.getByRole('button',{name:'Fechar',exact:true}).click();
    await page.getByRole('button',{name:'Revisão de escopo',exact:true}).click();
    await page.getByRole('button',{name:'Concluir atividade',exact:true}).click();
    await page.getByRole('button',{name:'Resultado da reunião',exact:true}).click();
    await page.getByRole('button',{name:'Registrar notas',exact:true}).click();
    await page.getByLabel('Notas da reunião',{exact:true}).fill('O cliente confirmou o prazo.');
    await page.getByRole('button',{name:'Salvar resultado',exact:true}).click();
    await page.getByText('O cliente confirmou o prazo.',{exact:true}).first().waitFor();
  } finally {
    await browser?.close();
    stopInference();
    if(server.listening)await new Promise(resolve=>server.close(resolve));
    await pool.end();
    await admin.end();
  }
});
