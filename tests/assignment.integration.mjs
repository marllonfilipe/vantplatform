import {test} from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import pg from 'pg';
import {chromium} from 'playwright-core';
import {servePage} from '../src/pages.mjs';
import {createApp} from '../src/app.mjs';
import {createPool,checkRuntime} from '../src/db.mjs';
import {featureRoutes} from '../src/routes.mjs';
import {hashPassword} from '../src/security.mjs';

test('gestor distribui leads e oportunidades com histórico de responsável',async()=>{
 assert.equal(process.env.APP_ENV,'test');
 const admin=new pg.Client({connectionString:process.env.ADMIN_DATABASE_URL});await admin.connect();
 const pool=createPool(process.env.DATABASE_URL),origin='http://127.0.0.1:3198';
 const server=createApp({pool,origin,featureRoutes,servePage,environment:'test'});
 let browser;
 const tenant=randomUUID(),other=randomUUID(),actor=randomUUID(),password=randomUUID(),email='gestor@example.invalid';
 try{
  await checkRuntime(pool);
  await admin.query("INSERT INTO vant.tenants(id,name) VALUES($1,'Fluxos'),($2,'Isolada')",[tenant,other]);
  await admin.query("INSERT INTO vant.members(tenant_id,id,email,name,role,password_hash) VALUES($1,$2,$3,'Gestor','owner',$4)",[tenant,actor,email,await hashPassword(password)]);
  await new Promise(resolve=>server.listen(3198,'127.0.0.1',resolve));
  const base='http://127.0.0.1:'+server.address().port+'/api/v1/';
  let cookie='';
  const call=(path,method='GET',data)=>fetch(base+path,{method,headers:{origin,cookie,'content-type':'application/json'},body:JSON.stringify(data)});
  const login=await call('auth/login','POST',{tenantId:tenant,email,password});assert.equal(login.status,200);
  cookie=login.headers.get('set-cookie').split(';')[0];
  const worker=t=>promisify(execFile)(process.execPath,['src/worker.mjs','--once'],{env:{...process.env,VANT_WORKER_TENANT:t},timeout:30000});
  const seller=randomUUID(),foreign=randomUUID();
  const memberHash=await hashPassword(randomUUID());
  await admin.query("INSERT INTO vant.members(tenant_id,id,email,name,role,password_hash) VALUES($1,$2,'seller@example.invalid','Vendas','seller',$5),($3,$4,'other@example.invalid','Outra empresa','seller',$5)",[tenant,seller,other,foreign,memberHash]);
  const spec={name:'Distribuição de leads',enabled:true,action_kind:'assign_owner',action_owner_id:seller};
  assert.equal((await call('automations','POST',{...spec,action_owner_id:foreign})).status,400);
  assert.equal((await call('automations','POST',{...spec,trigger_event:'lead_updated'})).status,400);
  browser=await chromium.launch({executablePath:process.env.CHROME_BIN??'/usr/bin/google-chrome',args:['--no-sandbox']});
  const page=await browser.newPage();
  await page.goto(origin);
  await page.getByLabel('Identificador da empresa').fill(tenant);
  await page.getByLabel('E-mail',{exact:true}).fill(email);
  await page.getByLabel('Senha').fill(password);
  await page.getByRole('button',{name:'Entrar'}).click();
  await page.getByRole('button',{name:'Automações',exact:true}).click();
  await page.getByRole('button',{name:'Criar fluxo'}).click();
  await page.getByLabel('Nome do fluxo').fill(spec.name);
  await page.getByLabel('Ação principal',{exact:true}).selectOption('assign_owner');
  await page.getByLabel('Novo responsável principal').selectOption(seller);
  await page.getByLabel('Ativar fluxo').check();
  await page.getByRole('button',{name:'Publicar versão'}).click();
  await page.getByRole('heading',{name:spec.name,exact:true}).waitFor();
  const flows=(await (await call('automations')).json()).items;
  assert.equal(flows.length,1);
  const flow=flows[0].id;assert.equal(flows[0].action_owner_id,seller);
  const leadRes=await call('crm/leads','POST',{name:'Lead para distribuição'});assert.equal(leadRes.status,201);
  const lead=(await leadRes.json()).id;
  await admin.query('UPDATE vant.members SET active=false WHERE tenant_id=$1 AND id=$2',[tenant,seller]);
  const runs=async()=>(await (await call('automations/runs')).json()).items;
  await worker(tenant);
  let [job]=await runs();assert.equal(job.history[0].reason,'owner_unavailable');
  assert.equal((await (await call('crm/leads/'+lead)).json()).owner_id,actor);
  await admin.query('UPDATE vant.members SET active=true WHERE tenant_id=$1 AND id=$2',[tenant,seller]);
  const updated=await call('automations/'+flow,'PUT',{...spec,expected_version:1,action_owner_id:actor});
  assert.equal(updated.status,200);
  await admin.query('UPDATE vant.jobs SET available_at=now() WHERE tenant_id=$1 AND id=$2',[tenant,job.id]);
  await Promise.all([worker(tenant),worker(tenant)]);
  [job]=await runs();
  assert.equal(job.payload.version,1);assert.equal(job.state,'done');
  assert.deepEqual(job.history.map(h=>h.outcome),['retry','assigned']);
  assert.deepEqual(job.history[1].assignment,{kind:'leads',record_id:lead,previous_owner_id:actor,owner_id:seller});
  assert.equal((await (await call('crm/leads/'+lead)).json()).owner_id,seller);
  const history=(await (await call('crm/leads/'+lead+'/history')).json()).items;
  assert.equal(history.filter(h=>h.action==='updated').length,1);
  assert.deepEqual(history.find(h=>h.action==='updated').changes.owner_id,{from:actor,to:seller});
  await page.getByRole('button',{name:'Automações',exact:true}).click();
  await page.getByText(spec.name+' · v1 · Concluído',{exact:true}).click();
  await page.getByText(/Tentativa 2 · Responsável atribuído/).waitFor();
  const dealSpec={name:'Triagem das oportunidades',trigger_event:'deal_created',enabled:true,
   task_title:'Triar oportunidade',source_filter:'Feira',else_kind:'assign_owner',else_owner_id:seller,
   steps:{otherwise:[{kind:'assign_owner',owner_id:seller},{kind:'task',title:'Conferir distribuição'}]}};
  assert.equal((await call('automations','POST',dealSpec)).status,201);
  const setup=await call('crm/pipelines','POST',{name:'Vendas',stages:['Contato','Proposta']});assert.equal(setup.status,201);
  const pipeline=(await setup.json()).id;
  const {stages}=(await (await call('crm/pipelines')).json()).items.find(p=>p.id===pipeline);
  const created=await call('crm/deals','POST',{name:'Renovação',source:'Site',pipeline_id:pipeline,stage_id:stages[0].id,amount_cents:2000,probability:50});
  assert.equal(created.status,201);const deal=(await created.json()).id;
  await worker(tenant);await worker(tenant);await worker(tenant);
  const assigned=(await runs()).find(j=>j.payload.deal===deal);
  assert.deepEqual(assigned.history.map(h=>h.outcome),['assigned','unchanged','created']);
  assert.ok(assigned.history.every(h=>h.branch==='otherwise'));
  assert.equal((await (await call('crm/deals/'+deal)).json()).owner_id,seller);
  assert.equal((await (await call('crm/activities/'+assigned.history[2].activity_id)).json()).owner_id,seller);
  const dealHistory=(await (await call('crm/deals/'+deal+'/history')).json()).items;
  assert.equal(dealHistory.filter(h=>h.action==='updated').length,1);
 }finally{
  await browser?.close();
  if(server.listening)await new Promise(resolve=>server.close(resolve));
  await pool.end();await admin.end();
 }
});
