import {test} from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import pg from 'pg';
import {chromium} from 'playwright-core';
import {servePage} from '../src/pages.mjs';
import {createApp} from '../src/app.mjs';
import {createPool,checkRuntime} from '../src/db.mjs';
import {featureRoutes} from '../src/routes.mjs';
import {hashPassword} from '../src/security.mjs';

test('evento real do CRM executa versão publicada no worker, com pausa, condição e retomada',async()=>{
 assert.equal(process.env.APP_ENV,'test');
 const admin=new pg.Client({connectionString:process.env.ADMIN_DATABASE_URL});await admin.connect();
 const pool=createPool(process.env.DATABASE_URL),origin='http://127.0.0.1:3197';
 const server=createApp({pool,origin,featureRoutes,servePage,environment:'test'});
 let browser;
 const tenant=randomUUID(),other=randomUUID(),actor=randomUUID(),password=randomUUID(),email='gestor@example.invalid';
 try{
  await checkRuntime(pool);
  await admin.query("INSERT INTO vant.tenants(id,name) VALUES($1,'Fluxos'),($2,'Isolada')",[tenant,other]);
  await admin.query("INSERT INTO vant.members(tenant_id,id,email,name,role,password_hash) VALUES($1,$2,$3,'Gestor','owner',$4)",[tenant,actor,email,await hashPassword(password)]);
  await new Promise(resolve=>server.listen(3197,'127.0.0.1',resolve));
  const base='http://127.0.0.1:'+server.address().port+'/api/v1/';
  let cookie='';
  const call=(path,method='GET',data)=>fetch(base+path,{method,headers:{origin,cookie,'content-type':'application/json'},body:JSON.stringify(data)});
  const login=await call('auth/login','POST',{tenantId:tenant,email,password});assert.equal(login.status,200);
  cookie=login.headers.get('set-cookie').split(';')[0];
  const worker=t=>promisify(execFile)(process.execPath,['src/worker.mjs','--once'],{env:{...process.env,VANT_WORKER_TENANT:t},timeout:30000});
  const spec={name:'Recepção',enabled:true,task_title:'Contato inicial',wait_minutes:0,source_filter:'Feira'};
  const published=await call('automations','POST',spec);assert.equal(published.status,201);
  const flow=(await published.json()).id,path='automations/'+flow;
  const leadResponse=await call('crm/leads','POST',{name:'Conta participante',source:'Feira'});assert.equal(leadResponse.status,201);
  const lead=(await leadResponse.json()).id;
  assert.equal((await call('crm/leads','POST',{name:'Outra origem',source:'Site'})).status,201);
  assert.equal((await call(path,'PUT',{...spec,enabled:false,expected_version:1})).status,200);
  await worker(tenant);
  const runs=async()=>(await (await call('automations/runs')).json()).items;
  assert.ok((await runs()).every(r=>r.state==='queued'));
  assert.equal((await call(path,'PUT',{...spec,expected_version:1})).status,409);
  assert.equal((await call(path,'PUT',{...spec,task_title:'Texto da revisão três',expected_version:2})).status,200);
  await worker(other);
  assert.deepEqual((await runs()).map(r=>r.attempts),[0,0]);
  await Promise.all([worker(tenant),worker(tenant)]);
  await worker(tenant);
  const processed=await runs();
  assert.deepEqual(processed.map(r=>r.history[0].outcome).sort(),['created','skipped']);
  assert.ok(processed.every(r=>r.state==='done'&&r.attempts===1&&r.payload.version===1));
  const tasks=await admin.query('SELECT title,owner_id FROM vant.activities WHERE tenant_id=$1 AND lead_id=$2',[tenant,lead]);
  assert.deepEqual(tasks.rows,[{title:'Contato inicial',owner_id:actor}]);
  assert.equal((await call(path,'PUT',{...spec,wait_minutes:30,expected_version:3})).status,200);
  assert.equal((await call('crm/leads','POST',{name:'Conta posterior',source:'Feira'})).status,201);
  await worker(tenant);
  assert.equal((await runs()).filter(r=>r.state==='queued').length,1);
  await admin.query("UPDATE vant.jobs SET available_at=now() WHERE tenant_id=$1 AND state='queued'",[tenant]);
  await admin.query('UPDATE vant.members SET active=false WHERE tenant_id=$1 AND id=$2',[tenant,actor]);
  await worker(tenant);
  await admin.query('UPDATE vant.members SET active=true WHERE tenant_id=$1 AND id=$2',[tenant,actor]);
  const retry=(await runs()).find(r=>r.state==='queued');
  assert.equal(retry.history[0].outcome,'retry');
  assert.equal(retry.history[0].reason,'author_unavailable');
  await admin.query("UPDATE vant.jobs SET available_at=now() WHERE tenant_id=$1 AND id=$2",[tenant,retry.id]);
  await worker(tenant);
  assert.deepEqual((await runs()).find(r=>r.id===retry.id).history.map(h=>h.outcome),['retry','created']);
  browser=await chromium.launch({executablePath:process.env.CHROME_BIN??'/usr/bin/google-chrome',args:['--no-sandbox']});
  const page=await browser.newPage();
  await page.goto(origin);
  await page.getByLabel('Identificador da empresa').fill(tenant);
  await page.getByLabel('E-mail',{exact:true}).fill(email);
  await page.getByLabel('Senha').fill(password);
  await page.getByRole('button',{name:'Entrar'}).click();
  await page.getByRole('button',{name:'Automações',exact:true}).click();
  await page.getByRole('button',{name:'Criar fluxo'}).click();
  await page.getByLabel('Nome do fluxo').fill('Retorno de evento');
  assert.equal(await page.getByLabel('Intervalo mínimo entre execuções (minutos)').inputValue(),'0');
  await page.getByLabel('Origem no CRM (opcional)').fill('Congresso');
  await page.getByText('Condições comerciais',{exact:true}).click();
  await page.getByRole('dialog').getByLabel('Responsável',{exact:true}).selectOption(actor);
  await page.getByLabel('Título da atividade principal').fill('Retornar ao participante');
  await page.getByLabel('Se as condições não forem atendidas').selectOption('reminder');
  await page.getByLabel('Título da atividade alternativa').fill('Revisar outro canal');
  await page.getByLabel('Prazo após a execução (minutos)').fill('45');
  const subsequent=page.locator('details').filter({has:page.getByText('Etapas após a ação principal',{exact:true})});
  await subsequent.locator('summary').click();
  await subsequent.getByRole('button',{name:'Adicionar etapa'}).click();
  await subsequent.getByLabel('Atividade da etapa',{exact:true}).selectOption('followup');
  await subsequent.getByLabel('Título da etapa',{exact:true}).fill('Acompanhar o retorno');
  await page.getByLabel('Ativar fluxo').check();
  await page.getByRole('button',{name:'Publicar versão'}).click();
  await page.getByRole('heading',{name:'Retorno de evento',exact:true}).waitFor();
  assert.equal((await call('crm/leads','POST',{name:'Visitante',source:'Congresso'})).status,201);
  await worker(tenant);
  await worker(tenant);
  await page.getByRole('button',{name:'Automações',exact:true}).click();
  await page.getByText('Retorno de evento · v1 · Concluído',{exact:true}).click();
  await page.getByText(/Tentativa 1 · Tarefa criada/).filter({visible:true}).first().waitFor();
  await page.getByText(/Tentativa 2 · Follow-up criado · etapa 2/).filter({visible:true}).first().waitFor();
  const alternateLead=await (await call('crm/leads','POST',{name:'Outra indicação',source:'Indicação'})).json();
  await worker(tenant);
  const alt=(await runs()).find(r=>r.payload.lead===alternateLead.id&&r.state==='done');
  assert.equal(alt.history[0].branch,'otherwise');
  assert.equal(alt.history[0].action_kind,'reminder');
  const {rows:[reminder]}=await admin.query("SELECT kind,title,round(extract(epoch FROM (due_at-created_at))/60)::int AS minutes FROM vant.activities WHERE tenant_id=$1 AND id=$2",[tenant,alt.history[0].activity_id]);
  assert.deepEqual(reminder,{kind:'reminder',title:'Revisar outro canal',minutes:45});
  const invalid=await call('automations','POST',{...spec,action_kind:'reminder'});
  assert.equal(invalid.status,400);
  assert.equal((await call('automations','POST',{...spec,source_filter:null,else_kind:'task',else_title:'Outro'})).status,400);
  const eventNames=['lead_updated','deal_created','deal_moved','deal_lost'];
  for(const trigger_event of eventNames){
   const response=await call('automations','POST',{...spec,name:trigger_event,trigger_event,source_filter:null,task_title:trigger_event});
   assert.equal(response.status,201);
  }
  assert.equal((await call('crm/leads/'+lead,'PATCH',{segment:'Industrial'})).status,200);
  assert.equal((await call('crm/leads/'+lead,'PATCH',{segment:'Industrial'})).status,200);
  assert.equal((await call('crm/leads/'+lead,'PATCH',{segment:'Comercial'})).status,200);
  const setup=await call('crm/pipelines','POST',{name:'Comercial',stages:['Entrada','Negociação']});
  assert.equal(setup.status,201);
  const pipeline=(await setup.json()).id;
  const {stages}= (await (await call('crm/pipelines')).json()).items.find(p=>p.id===pipeline);
  const createDeal=await call('crm/deals','POST',{name:'Contrato',pipeline_id:pipeline,stage_id:stages[0].id,amount_cents:35000,probability:50});
  assert.equal(createDeal.status,201);
  const deal=(await createDeal.json()).id;
  assert.equal((await call('crm/deals/'+deal,'PATCH',{stage_id:stages[1].id,status:'lost',loss_reason:'Sem orçamento'})).status,200);
  assert.equal((await call('crm/deals/'+deal,'PATCH',{loss_reason:'Sem orçamento disponível'})).status,200);
  for(let i=0;i<5;i++)await worker(tenant);
  const triggered=(await runs()).filter(r=>eventNames.includes(r.payload.event));
  assert.deepEqual(triggered.map(r=>r.payload.event).sort(),['deal_created','deal_lost','deal_moved','lead_updated','lead_updated']);
  assert.equal(new Set(triggered.map(r=>r.payload.occurrence)).size,5);
  assert.ok(triggered.every(r=>r.state==='done'&&r.history.length===1));
  const moved=triggered.find(r=>r.payload.event==='deal_moved');
  assert.equal(moved.payload.previous_stage,stages[0].id);
  assert.equal(moved.payload.stage,stages[1].id);
  const linked=await admin.query('SELECT deal_id,lead_id,owner_id FROM vant.activities WHERE tenant_id=$1 AND id=$2',[tenant,moved.history[0].activity_id]);
  assert.deepEqual(linked.rows,[{deal_id:deal,lead_id:null,owner_id:actor}]);
  for(const trigger_event of ['meeting_scheduled','meeting_completed']){
   assert.equal((await call('automations','POST',{...spec,name:trigger_event,trigger_event,source_filter:null,task_title:trigger_event})).status,201);
  }
  const addMeeting=await call('crm/activities','POST',{title:'Revisão da conta',kind:'meeting',deal_id:deal});
  assert.equal(addMeeting.status,201);
  const meeting=(await addMeeting.json()).id,activityPath='crm/activities/'+meeting;
  assert.ok(!(await runs()).some(r=>r.payload.meeting===meeting));
  assert.equal((await call(activityPath,'PATCH',{due_at:new Date(Date.now()+86400000).toISOString()})).status,200);
  assert.equal((await call(activityPath,'PATCH',{title:'Revisão comercial'})).status,200);
  assert.equal((await call(activityPath,'PATCH',{done_at:new Date().toISOString()})).status,200);
  assert.equal((await call(activityPath,'PATCH',{title:'Revisão encerrada'})).status,200);
  await Promise.all([worker(tenant),worker(tenant)]);
  const meetingRuns=(await runs()).filter(r=>r.payload.meeting===meeting);
  assert.deepEqual(meetingRuns.map(r=>r.payload.event).sort(),['meeting_completed','meeting_scheduled']);
  assert.ok(meetingRuns.every(r=>r.state==='done'&&r.history.length===1));
  const planned=await admin.query('SELECT title,deal_id,owner_id FROM vant.activities WHERE tenant_id=$1 AND id=ANY($2::uuid[]) ORDER BY title',[tenant,meetingRuns.map(r=>r.history[0].activity_id)]);
  assert.deepEqual(planned.rows.map(r=>[r.title,r.deal_id,r.owner_id]),[['meeting_completed',deal,actor],['meeting_scheduled',deal,actor]]);
  const conditionalFlow=await call('automations','POST',{...spec,trigger_event:'lead_updated',source_filter:null,conditions:{segment:'Varejo',tag:'prioridade',owner_id:actor},else_kind:'task',else_title:'Reavaliar cadastro'});
  assert.equal(conditionalFlow.status,201);
  const conditionalId=(await conditionalFlow.json()).id;
  assert.equal((await call('crm/leads/'+lead,'PATCH',{segment:'Varejo',tags:['prioridade']})).status,200);
  assert.equal((await call('crm/leads/'+lead,'PATCH',{segment:'Outro'})).status,200);
  for(let i=0;i<4;i++)await worker(tenant);
  const decisions=(await runs()).filter(r=>r.payload.flow===conditionalId);
  assert.equal(decisions.length,2);
  for(const decision of decisions){
   assert.equal(decision.history.length,1);
   assert.equal(decision.history[0].branch,decision.payload.facts.segment==='Varejo'?'match':'otherwise');
   assert.deepEqual(Object.keys(decision.payload.facts).sort(),['owner_id','segment','tag']);
  }
  const amountFlow=await call('automations','POST',{...spec,trigger_event:'deal_moved',source_filter:null,conditions:{min_cents:35000,stage_id:stages[0].id}});
  assert.equal(amountFlow.status,201);
  const amountId=(await amountFlow.json()).id;
  assert.equal((await call('crm/deals/'+deal,'PATCH',{stage_id:stages[0].id})).status,200);
  await worker(tenant);await worker(tenant);
  const amountRun=(await runs()).find(r=>r.payload.flow===amountId);
  assert.equal(amountRun.history[0].branch,'match');
  assert.equal(amountRun.payload.facts.min_cents,35000);
  assert.equal((await call('automations','POST',{...spec,conditions:{min_score:101}})).status,400);
  assert.equal((await call('automations','POST',{...spec,conditions:{bogus:true}})).status,400);
  await page.getByRole('button',{name:'Criar fluxo'}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Nome do fluxo').fill('Revisar ordem');
  await dialog.getByLabel('Título da atividade principal').fill('Triagem');
  await dialog.getByLabel('Origem no CRM (opcional)').fill('Indicação');
  await dialog.getByLabel('Se as condições não forem atendidas').selectOption('summarize');
  const pathEditor=dialog.locator('details').filter({has:page.getByText('Etapas após a ação principal',{exact:true})});
  await pathEditor.locator('summary').click();
  await pathEditor.getByRole('button',{name:'Adicionar etapa'}).click();
  await pathEditor.getByLabel('Título da etapa').first().fill('Enviar para revisão');
  await pathEditor.getByRole('button',{name:'Adicionar etapa'}).click();
  await pathEditor.getByLabel('Título da etapa').last().fill('Conferir dados');
  await pathEditor.getByLabel('Espera antes da etapa (minutos)').last().fill('15');
  await pathEditor.getByRole('button',{name:'Mover para cima'}).last().click();
  const diagram=dialog.getByRole('region',{name:'Mapa do fluxo'});
  const pathView=diagram.getByRole('region',{name:'Condições atendidas'});
  assert.deepEqual(await pathView.locator('li span').allTextContents(),['Triagem','Conferir dados','Enviar para revisão']);
  await pathView.getByText('Aguardar 15 min').waitFor();
  const altView=diagram.getByRole('region',{name:'Caminho alternativo'});await altView.getByText('Gerar resumo comercial').waitFor();
  await page.setViewportSize({width:390,height:844});
  const firstBox=await pathView.boundingBox(),secondBox=await altView.boundingBox();
  assert.ok(secondBox.y>=firstBox.y+firstBox.height-1);
  await dialog.getByRole('button',{name:'Publicar versão'}).click();
  await page.getByRole('heading',{name:'Revisar ordem',exact:true}).waitFor();
  const reordered=(await (await call('automations')).json()).items.find(f=>f.name==='Revisar ordem');
  assert.equal(reordered.enabled,false);
  assert.deepEqual(reordered.steps.match.map(s=>[s.title,s.wait_minutes]),[['Conferir dados',15],['Enviar para revisão',0]]);
 }finally{
  await browser?.close();
  if(server.listening)await new Promise(resolve=>server.close(resolve));
  await pool.end();await admin.end();
 }
});
